#!/usr/bin/env node
/**
 * تولیدکننده خودکار فایل‌های tokens/tokens.css و tokens/tokens.js
 * از تنها منبع حقیقت: tokens/design-tokens.json
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const srcJsonPath = path.join(rootDir, 'tokens', 'design-tokens.json');
const outCssPath = path.join(rootDir, 'tokens', 'tokens.css');
const outJsPath = path.join(rootDir, 'tokens', 'tokens.js');

const raw = JSON.parse(fs.readFileSync(srcJsonPath, 'utf8'));

const cssLines = [
  '/* AUTO-GENERATED BY scripts/build-tokens.mjs FROM tokens/design-tokens.json — DO NOT EDIT MANUALLY */',
  ':root {',
];

// 1. Brand primitives
for (const [k, v] of Object.entries(raw.color.brand)) {
  cssLines.push(`  --ds-color-${k}: ${v.$value};`);
}

// 2. Scales
for (const [group, entries] of Object.entries(raw.color.scale)) {
  for (const [step, v] of Object.entries(entries)) {
    cssLines.push(`  --ds-${group}-${step}: ${v.$value};`);
  }
}

// 3. Plate & Telemetry
for (const [k, v] of Object.entries(raw.color.plate)) {
  cssLines.push(`  --ds-plate-${k}: ${v.$value};`);
}
for (const [k, v] of Object.entries(raw.color.telemetry)) {
  cssLines.push(`  --ds-status-${k}: ${v.$value};`);
}

// 4. S-Module Spacing
for (const [k, v] of Object.entries(raw.spacing.scale)) {
  cssLines.push(`  --ds-space-${k}: ${v.$value};`);
}

// 5. Gradients
for (const [k, v] of Object.entries(raw.gradient)) {
  cssLines.push(`  --ds-grad-${k}: ${v.$value};`);
}

// 6. Typography
cssLines.push(`  --ds-font-sans: ${raw.typography.fontFamily.sans};`);
cssLines.push(`  --ds-font-mono: ${raw.typography.fontFamily.mono};`);
for (const [k, v] of Object.entries(raw.typography.weights)) {
  cssLines.push(`  --ds-weight-${k}: ${v};`);
}
for (const [k, v] of Object.entries(raw.typography.sizes)) {
  cssLines.push(`  --ds-text-${k}: ${v};`);
}

// 7. Geometry
for (const [k, v] of Object.entries(raw.geometry)) {
  cssLines.push(`  --ds-geo-${k}: ${v};`);
}

// 8. Motion
for (const [k, v] of Object.entries(raw.motion.easing)) {
  cssLines.push(`  --ds-ease-${k}: ${v};`);
}
for (const [k, v] of Object.entries(raw.motion.duration)) {
  cssLines.push(`  --ds-dur-${k}: ${v};`);
}

// 9. Radius & Elevation
for (const [k, v] of Object.entries(raw.radius)) {
  cssLines.push(`  --ds-radius-${k}: ${v};`);
}
for (const [k, v] of Object.entries(raw.elevation)) {
  cssLines.push(`  --ds-shadow-${k}: ${v};`);
}

// 10. Z-Layers
for (const [k, v] of Object.entries(raw.material3d.zLayers)) {
  cssLines.push(`  --ds-z-${k}: ${v};`);
}

// 11. Default Semantic Layer (Nocturnal Polarity)
for (const [k, v] of Object.entries(raw.semantic.nocturnal)) {
  cssLines.push(`  --ds-${k}: ${v};`);
}
cssLines.push('}');
cssLines.push('');

// 12. Daylight Polarity Override
cssLines.push('[data-polarity="daylight"] {');
for (const [k, v] of Object.entries(raw.semantic.daylight)) {
  cssLines.push(`  --ds-${k}: ${v};`);
}
cssLines.push('}');
cssLines.push('');

// Nocturnal explicit attribute (for nested cards inside daylight section)
cssLines.push('[data-polarity="nocturnal"] {');
for (const [k, v] of Object.entries(raw.semantic.nocturnal)) {
  cssLines.push(`  --ds-${k}: ${v};`);
}
cssLines.push('}');
cssLines.push('');

fs.writeFileSync(outCssPath, cssLines.join('\n'));

// Build JS module + Tailwind preset
const unwrapScale = (obj) =>
  Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, v.$value]));

const jsTokens = {
  color: {
    signalOrange: raw.color.brand['signal-orange'].$value,
    deepNavy: raw.color.brand['deep-navy'].$value,
    warmSand: raw.color.brand['warm-sand'].$value,
    orange: unwrapScale(raw.color.scale.orange),
    navy: unwrapScale(raw.color.scale.navy),
    sand: unwrapScale(raw.color.scale.sand),
    neutral: unwrapScale(raw.color.scale.neutral),
    plate: unwrapScale(raw.color.plate),
    telemetry: unwrapScale(raw.color.telemetry),
  },
  spacing: unwrapScale(raw.spacing.scale),
  gradients: Object.fromEntries(Object.entries(raw.gradient).map(([k, v]) => [k, v.$value])),
  typography: raw.typography,
  geometry: raw.geometry,
  material3d: raw.material3d,
  motion: raw.motion,
  radius: raw.radius,
  breakpoints: raw.breakpoints,
};

const tailwindPreset = {
  theme: {
    screens: raw.breakpoints,
    extend: {
      fontFamily: {
        sans: ['Peyda', 'Tahoma', 'sans-serif'],
      },
      colors: {
        signal: jsTokens.color.orange,
        navy: jsTokens.color.navy,
        sand: jsTokens.color.sand,
        telemetry: jsTokens.color.telemetry,
      },
      spacing: jsTokens.spacing,
      borderRadius: raw.radius,
      transitionTimingFunction: raw.motion.easing,
      transitionDuration: raw.motion.duration,
    },
  },
};

const jsContent = `/* AUTO-GENERATED BY scripts/build-tokens.mjs FROM tokens/design-tokens.json — DO NOT EDIT MANUALLY */
export const DESIGN_TOKENS = ${JSON.stringify(jsTokens, null, 2)};

export const tailwindFleetPreset = ${JSON.stringify(tailwindPreset, null, 2)};

export default DESIGN_TOKENS;
`;

fs.writeFileSync(outJsPath, jsContent);
console.log('[build-tokens] Generated tokens/tokens.css and tokens/tokens.js from tokens/design-tokens.json');
